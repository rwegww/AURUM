const calculation = ({
  id, gradeLevel, question, visual, formula, given, target, value,
  points, timeLimitSeconds, explanation, tolerance = 0.02,
}) => ({
  id,
  gradeLevel,
  gameType: 'calculation',
  question,
  payload: { visual, formula, given, target },
  answer: { value, tolerance },
  points,
  timeLimitSeconds,
  explanation,
});

const balancing = ({
  id, gradeLevel, question, reactants, products, coefficients,
  points, timeLimitSeconds, explanation, maxCoefficient = 12,
}) => ({
  id,
  gradeLevel,
  gameType: 'balancing',
  question,
  payload: {
    equation: { reactants, products },
    minCoefficient: 1,
    maxCoefficient,
  },
  answer: { coefficients },
  points,
  timeLimitSeconds,
  explanation,
});

const atomMatch = ({
  id, gradeLevel, question, moleculeId, formula, slots, choices,
  placements, points, timeLimitSeconds, explanation,
}) => ({
  id,
  gradeLevel,
  gameType: 'atom_match',
  question,
  payload: { moleculeId, formula, slots, choices },
  answer: { placements },
  points,
  timeLimitSeconds,
  explanation,
});

const electronMatch = ({
  id, gradeLevel, symbol, name, atomicNumber, shells, points, timeLimitSeconds,
}) => ({
  id,
  gradeLevel,
  gameType: 'electron_match',
  question: `Sắp xếp electron của nguyên tử ${name} (${symbol}) vào các lớp vỏ.`,
  payload: {
    symbol,
    atomicNumber,
    shellLabels: ['K', 'L', 'M', 'N'].slice(0, shells.length),
    modelHint: `${symbol} có ${atomicNumber} electron.`,
  },
  answer: { shells },
  points,
  timeLimitSeconds,
  explanation: `${symbol} phân bố electron theo lớp ${shells.join(', ')}.`,
});

